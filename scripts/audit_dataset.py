"""Audit the configured dataset and write a Markdown report (Member 3).

Usage (from the project root):

    python scripts/audit_dataset.py --config configs/dataset.json --out reports/dataset_audit.md

The report contains counts and statistics only. It never copies email text.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import dataset, quality, split_report  # noqa: E402


def build_report(config_path: str | Path, base_dir: str | Path | None = None) -> str:
    """Load the dataset described by ``config_path`` and return a Markdown audit report."""
    config = dataset.load_config(config_path)
    loaded = dataset.load_dataset(config, base_dir=base_dir)
    rows_read = len(loaded.valid) + len(loaded.errors)
    dedup = quality.deduplicate(loaded.valid, level="near")

    lines = [
        "# Dataset audit report",
        "",
        "_Generated by `scripts/audit_dataset.py`. Statistics only; no email text is included._",
        "",
        f"- Config: `{config_path}`",
        f"- Data rows read: **{rows_read}**",
        f"- Valid records: **{len(loaded.valid)}**",
        f"- Rejected rows: **{len(loaded.errors)}**",
        "",
    ]
    reasons = dataset.count_error_reasons(loaded.errors)
    if reasons:
        lines += ["### Rejected rows by reason", "", "| Reason | Rows |", "|---|---|"]
        lines += [f"| {reason} | {count} |" for reason, count in reasons.items()]
        lines.append("")
    lines.append(split_report.format_quality_markdown(quality.audit_quality(loaded.valid, level="near"), "Quality audit of valid records", loaded.valid))
    lines += [
        "## Duplicate removal (near-duplicate level)",
        "",
        f"- Records kept: **{len(dedup.records)}**",
        f"- Duplicates removed: **{split_report.count_removed(dedup)['duplicates']}**",
        f"- Records removed because identical content had different labels: **{split_report.count_removed(dedup)['conflicts']}**",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Audit the configured email dataset.")
    parser.add_argument("--config", default="configs/dataset.json", help="dataset config JSON")
    parser.add_argument("--out", default="reports/dataset_audit.md", help="where to write the report")
    args = parser.parse_args(argv)

    try:
        report = build_report(args.config)
    except dataset.DatasetError as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(report, encoding="utf-8")
    print(f"Wrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
