"""Train the baseline on the training split and report validation metrics (Member 5).

Usage (from the project root):

    python scripts/run_baseline.py --config configs/dataset.json --seed 42

Writes ``reports/baseline_metrics.md`` and ``reports/baseline_metrics.json``.
Only the training split is used for fitting. The test split is NOT touched here;
it is reserved for the final evaluation in Week 4.

All numbers in the report come from this run. Nothing is hard-coded.
"""

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import baseline, data_prep, dataset, metrics, split_report, splitting  # noqa: E402


def run_baseline(config_path: str | Path, seed: int = 42, base_dir: str | Path | None = None) -> dict:
    """Prepare the data, train the baseline and evaluate on the validation split.

    Returns:
        A dict with the setup (seed, sizes), the validation metrics and notes.
    """
    prepared = data_prep.prepare_splits(
        config_path, base_dir=base_dir, random_state=seed, duplicate_level=split_report.DEFAULT_LEVEL
    )
    train, validation = prepared.splits.train, prepared.splits.validation

    model = baseline.train_baseline(train, seed=seed)
    predicted = baseline.predict_labels(model, validation)
    result = metrics.compute_metrics([r["label"] for r in validation], predicted)

    return {
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "model": "TF-IDF (1-2 grams) + Logistic Regression (class_weight=balanced)",
        "seed": seed,
        "rows_read": prepared.valid_count + prepared.invalid_count,
        "rows_rejected": prepared.invalid_count,
        "duplicates_removed": split_report.count_removed(prepared.dedup)['duplicates'],
        "label_conflicts_removed": split_report.count_removed(prepared.dedup)['conflicts'],
        "split_sizes": prepared.splits.sizes(),
        "split_summary": split_report.summarize_split(prepared.splits),
        "evaluated_on": "validation",
        "validation_metrics": result,
    }


def to_markdown(report: dict) -> str:
    """Render the dict from ``run_baseline`` as a Markdown report."""
    lines = [
        "# Baseline results",
        "",
        "_Generated by `scripts/run_baseline.py`. Every number below comes from that run._",
        "",
        f"- Model: {report['model']}",
        f"- Seed: {report['seed']}",
        f"- Rows read: {report['rows_read']} (rejected: {report['rows_rejected']})",
        f"- Duplicates removed: {report['duplicates_removed']}; label-conflict records removed: {report['label_conflicts_removed']}",
        f"- Split sizes: {report['split_sizes']}",
        f"- Evaluated on: **{report['evaluated_on']} split** (the test split was not used)",
        "",
        metrics.format_metrics_markdown(report["validation_metrics"], "Validation metrics"),
        "## Limitations",
        "",
        "- This is a single run on one split; it gives no confidence interval.",
        "- The baseline only reads subject and body text.",
        "- Results depend entirely on the dataset chosen (see `docs/dataset-card.md`).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Train and evaluate the TF-IDF + Logistic Regression baseline.")
    parser.add_argument("--config", default="configs/dataset.json")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out-dir", default="reports")
    args = parser.parse_args(argv)

    try:
        report = run_baseline(args.config, seed=args.seed)
    except (dataset.DatasetError, ValueError, RuntimeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "baseline_metrics.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    (out_dir / "baseline_metrics.md").write_text(to_markdown(report), encoding="utf-8")
    print(f"Wrote baseline report to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
