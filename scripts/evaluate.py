"""Final evaluation on the held-out TEST split (Member 1).

Usage (from the project root, after ``python scripts/train.py``):

    python scripts/evaluate.py --config configs/dataset.json --model-dir models/latest

Run this once the model is final. It rebuilds the split with the seed stored in
the model's metadata, refuses to continue if the test set is not the one the
model was trained against, and writes ``reports/final_evaluation.md`` and
``.json``. The report contains IDs and statistics, never email text.
"""

import argparse
import json
import platform
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import benchmark, bundle, data_prep, dataset, keys, metrics, service, splitting  # noqa: E402


def calibration_table(scores: list[float], y_true: list[str], bins: int = 5) -> list[dict[str, Any]]:
    """Group scores into equal-width bins and report the real phishing rate in each.

    A useful risk score has higher observed phishing rates in higher bins.
    """
    if len(scores) != len(y_true) or not scores:
        raise ValueError("scores and y_true must be non-empty and the same length.")
    table = []
    for index in range(bins):
        low, high = index / bins, (index + 1) / bins
        members = [
            label for score, label in zip(scores, y_true)
            if low <= score < high or (index == bins - 1 and score == 1.0)
        ]
        phishing = sum(label == "phishing" for label in members)
        table.append(
            {
                "range": f"{low:.1f}-{high:.1f}",
                "emails": len(members),
                "phishing": phishing,
                "observed_phishing_rate": round(phishing / len(members), 4) if members else None,
            }
        )
    return table


def run_evaluation(
    config_path: str | Path, model_dir: str | Path, base_dir: str | Path | None = None
) -> dict[str, Any]:
    """Evaluate the saved model on the test split and return the report dict.

    Raises:
        FileNotFoundError: If no trained model exists in ``model_dir``.
        RuntimeError: If the rebuilt test split differs from the one recorded at training time.
    """
    loaded = bundle.load_bundle(model_dir)
    meta = loaded.metadata
    prepared = data_prep.prepare_splits(
        config_path,
        base_dir=base_dir,
        train_size=meta["ratios"][0],
        validation_size=meta["ratios"][1],
        test_size=meta["ratios"][2],
        random_state=meta["seed"],
        duplicate_level=meta["dedup_level"],
    )
    test = prepared.splits.test
    if splitting.fingerprint_split(prepared.splits, meta["dedup_level"]) != meta["split_fingerprint"]:
        raise RuntimeError(
            "The test split does not match the one recorded when the model was trained. "
            "The dataset, seed or preprocessing changed; retrain with scripts/train.py."
        )

    threshold = meta["threshold"]
    scores = [loaded.predict_score(record) for record in test]
    predicted = ["phishing" if score >= threshold else "legitimate" for score in scores]
    y_true = [record["label"] for record in test]
    result = metrics.compute_metrics(y_true, predicted)

    wrong = [(keys.record_id(r), t, p) for r, t, p in zip(test, y_true, predicted) if t != p]
    sample = test[: min(len(test), 50)]
    latency = benchmark.measure_latency(lambda r: service.analyze_record(r, loaded), sample[0], runs=20)
    throughput = benchmark.time_calls(lambda r: service.analyze_record(r, loaded), sample)

    return {
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "model_version": loaded.version,
        "model_name": meta["model_name"],
        "seed": meta["seed"],
        "threshold": threshold,
        "test_size": len(test),
        "split_fingerprint": meta["split_fingerprint"],
        "test_metrics": result,
        "false_positive_ids": [i for i, t, p in wrong if t == "legitimate"],
        "false_negative_ids": [i for i, t, p in wrong if t == "phishing"],
        "calibration": calibration_table(scores, y_true),
        "latency_single_message": latency,
        "throughput_batch": {**throughput, "batch_size": len(sample)},
        "machine": f"{platform.system()} {platform.release()}, Python {platform.python_version()}",
    }


def to_markdown(report: dict[str, Any]) -> str:
    """Render the evaluation as a Markdown report."""
    lat, thr = report["latency_single_message"], report["throughput_batch"]
    lines = [
        "# Final evaluation (held-out test split)",
        "",
        "_Generated by `scripts/evaluate.py`. Every number comes from that run._",
        "",
        f"- Model: `{report['model_name']}` (version `{report['model_version']}`)",
        f"- Seed: {report['seed']}   Decision threshold: {report['threshold']}",
        f"- Test emails: {report['test_size']}   Split fingerprint: `{report['split_fingerprint']}`",
        "",
        metrics.format_metrics_markdown(report["test_metrics"], "Test-set metrics"),
        "## Errors (IDs only)",
        "",
        f"- False positives (legitimate flagged as phishing): {len(report['false_positive_ids'])} {report['false_positive_ids']}",
        f"- False negatives (phishing missed): {len(report['false_negative_ids'])} {report['false_negative_ids']}",
        "",
        "## Risk-score usefulness (calibration table)",
        "",
        "| Score range | Emails | Phishing | Observed phishing rate |",
        "|---|---|---|---|",
    ]
    for row in report["calibration"]:
        rate = "n/a" if row["observed_phishing_rate"] is None else row["observed_phishing_rate"]
        lines.append(f"| {row['range']} | {row['emails']} | {row['phishing']} | {rate} |")
    lines += [
        "",
        "## Speed",
        "",
        f"- Single message (median / 95th percentile): {lat['median_ms']:.2f} ms / {lat['p95_ms']:.2f} ms",
        f"- Batch of {thr['batch_size']}: {thr['messages_per_second']:.1f} messages per second",
        f"- Measured on: {report['machine']}",
        "",
        "## Limitations",
        "",
        "- Performance by phishing category or source was not evaluated: the schema has no such column.",
        "- Small test sets give wide uncertainty; one split and one seed only.",
        "- Calibration bins with few emails are noisy.",
        "- Results describe this dataset only (see `docs/dataset-card.md`) and may not carry over to other email.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Evaluate the trained model on the held-out test split.")
    parser.add_argument("--config", default="configs/dataset.json")
    parser.add_argument("--model-dir", default="models/latest")
    parser.add_argument("--out-dir", default="reports")
    args = parser.parse_args(argv)

    try:
        report = run_evaluation(args.config, args.model_dir)
    except (dataset.DatasetError, FileNotFoundError, ValueError, RuntimeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "final_evaluation.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    (out_dir / "final_evaluation.md").write_text(to_markdown(report), encoding="utf-8")
    print(f"Wrote final evaluation to {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
