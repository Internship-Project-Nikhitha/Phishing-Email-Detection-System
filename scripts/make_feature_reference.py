"""Write docs/feature-reference.md from the registered features (Member 4).

Run from the project root::

    python scripts/make_feature_reference.py          # rewrite the document
    python scripts/make_feature_reference.py --check  # exit 1 if it is out of date

The table is generated from the code, so it cannot drift from the real features.
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from src.features import pipeline  # noqa: E402

OUTPUT = ROOT / "docs" / "feature-reference.md"
GROUP_TITLES = {"sender": "Sender features", "url": "URL features", "text": "Text features"}


def build_markdown() -> str:
    """Return the Markdown reference for every feature, grouped by module."""
    descriptions = pipeline.feature_descriptions()
    names = pipeline.feature_names()
    lines = [
        "# Feature reference",
        "",
        "Generated by `scripts/make_feature_reference.py` from the registered features. Do not edit by hand;",
        "change the feature's description in `src/features/` and run the script again.",
        "",
        f"There are {len(names)} hand-built features. Every feature is one number per email. Links are only read as text.",
        "",
    ]
    for prefix, title in GROUP_TITLES.items():
        group = [name for name in names if name.startswith(prefix + "_")]
        lines += [f"## {title} ({len(group)})", "", "| Feature | What it measures |", "|---|---|"]
        lines += [f"| `{name}` | {descriptions[name].replace('|', '/')} |" for name in group]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = build_markdown()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("docs/feature-reference.md is out of date. Run: python scripts/make_feature_reference.py")
            return 1
        print("docs/feature-reference.md is up to date.")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
