"""Train and compare the candidate models (Member 5).

Usage (from the project root):

    python scripts/train.py --config configs/dataset.json --seed 42

What it does:

1. Prepares the data (load, clean, de-duplicate, leakage-safe split).
2. For each candidate model, tunes on the validation split and records metrics.
3. Picks the best model by validation F1 (ties: lower false-positive rate).
4. Writes ``reports/model_comparison.md`` and ``.json`` and saves the best model
   to ``models/latest/``.

The TEST split is never used here. It is reserved for the final evaluation
(``scripts/evaluate.py``). All numbers come from the run; nothing is hard-coded.
"""

import argparse
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import bundle, data_prep, dataset, metrics, models, split_report, splitting  # noqa: E402
from src.features import pipeline  # noqa: E402


def run_training(
    config_path: str | Path,
    seed: int = 42,
    base_dir: str | Path | None = None,
    model_names: list[str] | None = None,
    max_features: int = 20000,
    threshold: float = 0.5,
) -> tuple[dict[str, Any], bundle.ModelBundle]:
    """Tune every candidate on the validation split and return (report, best bundle)."""
    prepared = data_prep.prepare_splits(
        config_path, base_dir=base_dir, random_state=seed, duplicate_level=split_report.DEFAULT_LEVEL
    )
    train, validation = prepared.splits.train, prepared.splits.validation
    specs = models.available_models()
    names = model_names or list(specs)
    unknown = [name for name in names if name not in specs]
    if unknown:
        raise ValueError(f"Unknown model names {unknown}. Available: {list(specs)}")

    results = []
    best: models.TuningResult | None = None
    for name in names:
        started = time.perf_counter()
        tuned = models.tune_model(specs[name], train, validation, seed, max_features, threshold)
        seconds = time.perf_counter() - started
        results.append(
            {
                "name": name,
                "description": specs[name].description,
                "mode": specs[name].mode,
                "chosen_params": tuned.params,
                "candidates_tried": tuned.candidates_tried,
                "validation_metrics": tuned.validation_metrics,
                "tuning_seconds": round(seconds, 2),
            }
        )
        key = (tuned.validation_metrics["f1"], -tuned.validation_metrics["false_positive_rate"])
        if best is None or key > (best.validation_metrics["f1"], -best.validation_metrics["false_positive_rate"]):
            best = tuned
    assert best is not None

    version = bundle.make_version(best.spec_name)
    metadata = {
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "seed": seed,
        "dataset_config": str(config_path),
        "ratios": list(split_report.DEFAULT_RATIOS),
        "dedup_level": split_report.DEFAULT_LEVEL,
        "split_sizes": prepared.splits.sizes(),
        "split_fingerprint": splitting.fingerprint_split(prepared.splits, split_report.DEFAULT_LEVEL),
        "mode": best.model.mode,
        "params": best.params,
        "threshold": threshold,
        "engineered_feature_count": len(pipeline.feature_names()),
        "total_feature_count": len(best.model.builder.feature_names),
        "validation_metrics": best.validation_metrics,
        "evaluated_on": "validation (test split untouched)",
    }
    report = {
        "created_at": metadata["created_at"],
        "seed": seed,
        "split_sizes": metadata["split_sizes"],
        "threshold": threshold,
        "models": results,
        "selected_model": best.spec_name,
        "selected_version": version,
    }
    return report, bundle.ModelBundle(model=best.model, version=version, metadata=metadata)


def to_markdown(report: dict[str, Any]) -> str:
    """Render the training report as a Markdown comparison table."""
    lines = [
        "# Model comparison (validation split)",
        "",
        "_Generated by `scripts/train.py`. Every number comes from that run. The test split was not used._",
        "",
        f"- Seed: {report['seed']}   Decision threshold: {report['threshold']}",
        f"- Split sizes: {report['split_sizes']}",
        "",
        "| Model | Params | Precision | Recall | F1 | False-positive rate | False-negative rate |",
        "|---|---|---|---|---|---|---|",
    ]
    for item in report["models"]:
        m = item["validation_metrics"]
        lines.append(
            f"| {item['name']} | {item['chosen_params']} | {m['precision']:.4f} | {m['recall']:.4f} "
            f"| {m['f1']:.4f} | {m['false_positive_rate']:.4f} | {m['false_negative_rate']:.4f} |"
        )
    lines += [
        "",
        f"**Selected model:** `{report['selected_model']}` (version `{report['selected_version']}`), "
        "chosen by highest validation F1, ties broken by lower false-positive rate.",
        "",
        "## Notes and limitations",
        "",
        "- Models were tuned only on the validation split; the test split is reserved for the final evaluation.",
        "- One split and one seed: differences between close models may not be meaningful.",
        "- Small validation sets give noisy metrics; check the confusion counts in the JSON report.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Train and compare phishing detection models.")
    parser.add_argument("--config", default="configs/dataset.json")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--model-dir", default="models/latest")
    parser.add_argument("--out-dir", default="reports")
    args = parser.parse_args(argv)

    try:
        report, best = run_training(args.config, seed=args.seed)
    except (dataset.DatasetError, ValueError, RuntimeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "model_comparison.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    (out_dir / "model_comparison.md").write_text(to_markdown(report), encoding="utf-8")
    bundle.save_bundle(best, args.model_dir)
    print(f"Selected {report['selected_model']}. Reports in {out_dir}, model in {args.model_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
