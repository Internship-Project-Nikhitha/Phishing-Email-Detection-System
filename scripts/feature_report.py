"""Summarize how the hand-built features differ between classes (Member 4).

Usage (from the project root):

    python scripts/feature_report.py --config configs/dataset.json

Uses the TRAINING split only and writes ``reports/feature_stats.md`` with the
average value of every feature for phishing and legitimate emails. This helps
check that a feature behaves as intended; it is not a model result.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src import data_prep, dataset  # noqa: E402
from src.features import pipeline  # noqa: E402


def class_means(records: list[dict[str, str]]) -> dict[str, dict[str, float]]:
    """Return ``{feature: {'phishing': mean, 'legitimate': mean}}`` for the records."""
    sums: dict[str, dict[str, float]] = {name: {"phishing": 0.0, "legitimate": 0.0} for name in pipeline.feature_names()}
    counts = {"phishing": 0, "legitimate": 0}
    for record in records:
        counts[record["label"]] += 1
        for name, value in pipeline.extract_all(record).items():
            sums[name][record["label"]] += value
    return {
        name: {label: (total / counts[label] if counts[label] else 0.0) for label, total in per_label.items()}
        for name, per_label in sums.items()
    }


def to_markdown(means: dict[str, dict[str, float]], train_size: int) -> str:
    """Render class means as a Markdown table."""
    descriptions = pipeline.feature_descriptions()
    lines = [
        "# Feature statistics (training split only)",
        "",
        f"_Generated by `scripts/feature_report.py` from {train_size} training emails._",
        "",
        "| Feature | Mean (phishing) | Mean (legitimate) | Meaning |",
        "|---|---|---|---|",
    ]
    for name, per_label in means.items():
        lines.append(f"| {name} | {per_label['phishing']:.3f} | {per_label['legitimate']:.3f} | {descriptions[name]} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Report feature averages per class on the training split.")
    parser.add_argument("--config", default="configs/dataset.json")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", default="reports/feature_stats.md")
    args = parser.parse_args(argv)

    try:
        train = data_prep.prepare_splits(
            args.config, random_state=args.seed, duplicate_level="near"
        ).splits.train
    except (dataset.DatasetError, ValueError, RuntimeError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(to_markdown(class_means(train), len(train)), encoding="utf-8")
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
