"""Generate ``docs/model-card.md`` from the real training outputs (Member 5).

Usage (from the project root, after ``python scripts/train.py``):

    python scripts/make_model_card.py

Reads ``models/latest/model_meta.json`` and ``reports/model_comparison.json`` and
writes a model card whose numbers are copied from those files, never typed by hand.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any


def build_model_card(meta: dict[str, Any], comparison: dict[str, Any]) -> str:
    """Return the Markdown model card for the selected model."""
    metrics = meta["validation_metrics"]
    lines = [
        "# Model card",
        "",
        "_Generated by `scripts/make_model_card.py` from the training outputs._",
        "",
        "## Model",
        "",
        f"- Name: `{meta['model_name']}`",
        f"- Version: `{meta['version']}`",
        f"- Trained at: {meta['created_at']}",
        f"- Feature mode: {meta['mode']} ({meta['total_feature_count']} input features, "
        f"{meta['engineered_feature_count']} of them hand-built)",
        f"- Parameters: {meta['params']}",
        f"- Decision threshold: {meta['threshold']}",
        "",
        "## Training setup",
        "",
        f"- Dataset config: `{meta['dataset_config']}`",
        f"- Seed: {meta['seed']}   Duplicate level: {meta['dedup_level']}   Ratios: {meta['ratios']}",
        f"- Split sizes: {meta['split_sizes']}",
        f"- Evaluated on: {meta['evaluated_on']}",
        "",
        "## Validation metrics",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Precision | {metrics['precision']:.4f} |",
        f"| Recall | {metrics['recall']:.4f} |",
        f"| F1-score | {metrics['f1']:.4f} |",
        f"| False-positive rate | {metrics['false_positive_rate']:.4f} |",
        f"| False-negative rate | {metrics['false_negative_rate']:.4f} |",
        "",
        "## Compared candidates (validation split)",
        "",
        "| Model | F1 | False-positive rate |",
        "|---|---|---|",
    ]
    for item in comparison["models"]:
        m = item["validation_metrics"]
        lines.append(f"| {item['name']} | {m['f1']:.4f} | {m['false_positive_rate']:.4f} |")
    lines += [
        "",
        "## Intended use and limits",
        "",
        "- Intended use: ranking emails for human review and explaining suspicious indicators.",
        "- Not for automatic blocking or deleting email without human review.",
        "- Final held-out test results are in `reports/final_evaluation.md`.",
        "- Explanations for linear and Naive Bayes models show direction; for Random Forest they show relevance only.",
        "- Trained on one dataset; behaviour on other email sources is unknown.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/model-card.md from training outputs.")
    parser.add_argument("--meta", default="models/latest/model_meta.json")
    parser.add_argument("--comparison", default="reports/model_comparison.json")
    parser.add_argument("--out", default="docs/model-card.md")
    args = parser.parse_args(argv)

    try:
        meta = json.loads(Path(args.meta).read_text(encoding="utf-8"))
        comparison = json.loads(Path(args.comparison).read_text(encoding="utf-8"))
        card = build_model_card(meta, comparison)
    except (OSError, KeyError, json.JSONDecodeError) as error:
        print(f"Error: could not build the model card ({error}). Run python scripts/train.py first.", file=sys.stderr)
        return 1

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(card, encoding="utf-8")
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
